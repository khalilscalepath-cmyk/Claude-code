#!/usr/bin/env bash
# Cut a walkthrough clip into the scroll-scrub frame sequence.
#
#   tools/build-frames.sh <video-file-or-url> [frame-count] [width]
#
# Writes assets/frames/frame-0000.webp... and rewrites assets/frames/manifest.json.
# The page picks the sequence up automatically on the next load.
#
# Source the clip from Carmel's own footage. Jamie's YouTube walkthrough is
# "Luxury Remodelers in Scottsdale AZ" (watch?v=xUe9ZmMqNok); yt-dlp can pull it
# once youtube.com is reachable from this environment.
set -euo pipefail

SRC="${1:?usage: build-frames.sh <video-file-or-url> [frame-count] [width]}"
COUNT="${2:-72}"
WIDTH="${3:-1280}"

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FRAMES="$HERE/assets/frames"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

if [[ "$SRC" =~ ^https?:// ]]; then
  echo "Downloading $SRC"
  yt-dlp -f "bv*[height<=1080]+ba/b[height<=1080]" --merge-output-format mp4 \
         -o "$WORK/clip.%(ext)s" "$SRC"
  CLIP="$(find "$WORK" -maxdepth 1 -name 'clip.*' | head -1)"
else
  CLIP="$SRC"
fi

DURATION="$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$CLIP")"
FPS="$(python3 -c "print(max(0.1, $COUNT / float($DURATION)))")"

echo "Cutting $COUNT frames at ${WIDTH}px from ${DURATION}s of footage"
rm -f "$FRAMES"/frame-*.webp
ffmpeg -v error -i "$CLIP" \
  -vf "fps=$FPS,scale=$WIDTH:-2" -frames:v "$COUNT" \
  -q:v 72 "$FRAMES/frame-%04d.webp"

python3 - "$FRAMES" <<'PY'
import json, pathlib, sys
frames_dir = pathlib.Path(sys.argv[1])
frames = sorted(p.name for p in frames_dir.glob("frame-*.webp"))
manifest = frames_dir / "manifest.json"
manifest.write_text(json.dumps({
    "frames": frames,
    "note": "Generated by tools/build-frames.sh from Carmel's own walkthrough footage.",
}, indent=2) + "\n", encoding="utf-8")
print(f"{len(frames)} frames written to {manifest}")
PY
